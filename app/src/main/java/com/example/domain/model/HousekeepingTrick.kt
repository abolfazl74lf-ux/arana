    fun getTricksForRoom(room: RoomType): List<HousekeepingTrick> {
        return tricks.filter { it.room == room }
    }

    fun getDailyTrickForRoom(room: RoomType, daySeedOffset: Int = 0): HousekeepingTrick {
        val roomTricks = getTricksForRoom(room)
        if (roomTricks.isEmpty()) {
            return HousekeepingTrick(
                id = "default_${room.id}",
                room = room,
                title = "نکته خانه داری ${room.titleFa}",
                shortTip = "نظم و تمیزی مداوم باعث آرامش و افزایش طول عمر وسایل می‌شود.",
                fullInstructions = "نگهداری دوره‌ای و روزانه ده دقیقه برای هر بخش خانه، از تجمع کارهای سنگین در آخر هفته جلوگیری می‌کند.",
                tag = "روتین عمومی"
            )
        }
        val index = (daySeedOffset.coerceAtLeast(0)) % roomTricks.size
        return roomTricks[index]
    }
